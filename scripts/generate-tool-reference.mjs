// Writes skills/<cli-bin>/reference/tools.md from the CLI's own `tools` and
// `describe` output, so the skill's parameter tables can never drift from the
// registered zod schemas. Run after `npm run build`:
//
//   npm run skill:reference
//
// Only the compact index is written (one-line summary plus parameter table);
// the full usage notes stay behind `<bin> describe <tool>`, which the skill
// tells the agent to run when it needs them.
import { execFileSync } from 'child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const [bin, entry] = Object.entries(pkg.bin).find(([name]) => name.endsWith('-cli'));

function cli(...args) {
  const out = execFileSync(process.execPath, [join(root, entry), ...args], {
    encoding: 'utf8',
    env: { ...process.env, LOG_LEVEL: 'error' },
  });
  const envelope = JSON.parse(out);
  if (!envelope.ok) throw new Error(`${bin} ${args.join(' ')} failed: ${envelope.error?.message}`);
  return envelope.data;
}

const cell = (text, max = 220) => {
  const flat = String(text ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
};

function typeOf(schema) {
  if (!schema) return '';
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(' \\| ');
  if (schema.anyOf) return [...new Set(schema.anyOf.map(typeOf))].join(' \\| ');
  if (schema.type === 'array') return `array<${typeOf(schema.items) || 'any'}>`;
  return Array.isArray(schema.type) ? schema.type.join(' \\| ') : schema.type ?? 'object';
}

const tools = cli('tools').tools;
const lines = [
  `# ${bin} tool reference`,
  '',
  `Generated by \`npm run skill:reference\` from \`${bin} describe <tool>\`; do not edit by hand.`,
  `${tools.length} tools, version ${pkg.version}. Full usage notes for any tool: \`${bin} describe <tool>\`.`,
  '',
  '| Tool | Summary | Required |',
  '|---|---|---|',
  ...tools.map((t) => `| \`${t.name}\` | ${cell(t.summary, 160)} | ${t.required.map((p) => `\`${p}\``).join(', ') || '—'} |`),
  '',
];

for (const { name } of tools) {
  const { description, inputSchema } = cli('describe', name);
  const required = new Set(inputSchema.required ?? []);
  const props = Object.entries(inputSchema.properties ?? {});
  lines.push(`## ${name}`, '', cell(description.split('\n').find((l) => l.trim()) ?? description, 400), '');
  if (props.length === 0) {
    lines.push('No parameters.', '');
    continue;
  }
  lines.push('| Parameter | Type | Required | Default | Description |', '|---|---|---|---|---|');
  for (const [param, schema] of props) {
    const def = schema.default === undefined ? '' : `\`${JSON.stringify(schema.default)}\``;
    lines.push(`| \`${param}\` | ${typeOf(schema)} | ${required.has(param) ? 'yes' : ''} | ${def} | ${cell(schema.description)} |`);
  }
  lines.push('');
}

const outDir = join(root, 'skills', bin, 'reference');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tools.md'), `${lines.join('\n').trimEnd()}\n`);
console.error(`wrote skills/${bin}/reference/tools.md (${tools.length} tools)`);
